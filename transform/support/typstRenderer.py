# -*- coding: utf-8 -*-
#
#   Renders a print-quality PDF via Typst (https://typst.app), matching the
#   layout of the ConTeXt renderer's output: 6x9in Trade pages, TeX Gyre
#   Pagella, a 4in text block with chapter/verse numbers in the left
#   margin, 13pt baselines with packed indented paragraphs, italic centred
#   section heads with small-caps opening phrases, right-page book starts,
#   running heads, footnotes, cover page and table of contents.
#
#   The typst binary is found on PATH or via the TYPST environment
#   variable; extra font directories via TYPST_FONT_PATH. Pagella is taken
#   from the vendored ConTeXt tree when present.
#

import os
import shutil
import subprocess

import abstractRenderer

TYPST_SPECIALS = '\\#$[]*_`@<>/'


def escapeText(text):
    for ch in TYPST_SPECIALS:
        text = text.replace(ch, '\\' + ch)
    if text[:1] in ('=', '-', '+'):
        text = '\\' + text
    return text


PREAMBLE = '''// Generated by usfm-tools typstRenderer - do not edit.
#let bookmk = state("book", "")
#let chaptermk = state("chapter", "")
#let sectionmk = state("section", "")

#set text(font: ("{{{bodyFont}}}", "Georgia"), size: {{{bodyFontSize}}})
#set par(justify: true, leading: 5pt, spacing: 5pt,
         first-line-indent: 1em)
#set footnote.entry(indent: 0.5em)
#set heading(numbering: none)
#set outline.entry(fill: none)

// Chapter and verse numbers in the left margin, right-aligned to end
// 0.1in before the text block (text block starts 1in from page left).
// An inline zero-width box keeps the number on the text baseline; move()
// shifts only where it is painted, out into the margin.
#let mnum(body) = context {
  let pos = here().position()
  let w = measure(body).width
  box(width: 0pt, move(dx: 0.68in - w - pos.x, body))
}
#let C(n) = mnum(text(weight: "bold", size: 10.5pt)[#n])
#let V(n) = mnum(text(size: 7.5pt)[#n])

// Poetry: n indent steps left, one step right, ragged.
#let poem(n, body) = pad(left: 1.5em * (1 + n), right: 1.5em,
  par(justify: false, hanging-indent: 1.5em, first-line-indent: 0em, body))

#set page(
  width: 6in, height: 9in,
  margin: (left: 0.75in, right: 1.25in, top: 1.4in, bottom: 1.1in),
  header-ascent: 0.45in,
  footer-descent: 0.3in,
  header: context {
    // No running head on pages that open a new book (the hidden
    // book headings mark those pages).
    let bookpages = query(heading.where(level: 1)).map(h => h.location().page())
    if not bookpages.contains(here().page()) {
      set text(size: 9pt)
      emph(sectionmk.get())
      h(1fr)
      bookmk.get() + " " + chaptermk.get()
    }
  },
  footer: context {
    set text(size: 9pt)
    counter(page).display("1")
  },
)
{{{cover}}}
'''


class Renderer(abstractRenderer.AbstractRenderer):

    def __init__(self, inputDir, outputDir, outputName, config):
        self.identity = 'typst renderer'
        self.outputFilename = os.path.join(outputDir, outputName + '.pdf')
        self.outputDescription = self.outputFilename
        abstractRenderer.AbstractRenderer.__init__(self, inputDir, outputDir, outputName, config)
        self.inputDir = inputDir
        self.outputDir = outputDir
        self.typFilename = os.path.join(outputDir, outputName + '.typ')
        # Document state
        self.chunks = []
        self.para = None          # pieces of the open paragraph, or None
        self.paraKind = 'p'       # p | q1 | q2 | q3 | d | pi
        self.narrower = False
        self.pendingSmallCaps = False
        self.cachedChapter = ''
        self.pendingVerse = ''
        self.afterTitle = False

    def render(self):
        self.loadUSFM(self.inputDir)
        preamble = PREAMBLE.replace('{{{cover}}}', self.coverText())
        preamble = preamble.replace('{{{bodyFont}}}', self.config.get('Typst', 'bodyFont'))
        preamble = preamble.replace('{{{bodyFontSize}}}', self.config.get('Typst', 'bodyFontSize'))
        self.chunks.append(preamble)
        self.run()
        self.closeParagraph()
        self.stopNarrower()
        with open(self.typFilename, 'w', encoding='utf-8') as f:
            f.write(''.join(self.chunks))
        self.compile()
        if self.config.get('Typst', 'saveTypst') != 'true':
            os.remove(self.typFilename)
            coverPng = os.path.join(self.outputDir, 'cover.png')
            if os.path.exists(coverPng):
                os.remove(coverPng)
        self.logger.info('Wrote ' + self.outputFilename)

    def coverText(self):
        cover = self.config.get('Typst', 'coverPage')
        if not os.path.exists(cover):
            return ''
        # Rasterise the cover PDF with QuickLook; skip the cover if the
        # conversion is unavailable (e.g. not on macOS).
        try:
            subprocess.run(['qlmanage', '-t', '-s', '1800', cover, '-o', self.outputDir],
                           capture_output=True, check=True)
            png = os.path.join(self.outputDir, os.path.basename(cover) + '.png')
            target = os.path.join(self.outputDir, 'cover.png')
            os.replace(png, target)
        except Exception:
            self.logger.warning('Cover conversion unavailable; building without cover')
            return ''
        # Natural-size figure on an ordinary page, centred on the paper,
        # like ConTeXt's \externalfigure, followed by its \page[right]
        # (a plain break in the singlesided layout).
        return ('#align(center, move(dx: 0.25in, dy: -0.15in, image("cover.png", width: 4.8in)))\n'
                '#pagebreak()\n')

    def compile(self):
        binary = os.environ.get('TYPST') or self.config.get('Typst', 'binary')
        typst = binary if os.path.isabs(binary) and os.path.exists(binary) \
            else shutil.which(binary)
        if not typst:
            raise RuntimeError('typst binary "%s" not found: install typst, '
                               'set [Typst] binary in the config, or set TYPST'
                               % binary)
        cmd = [typst, 'compile']
        pagella = os.path.join(os.path.dirname(os.path.realpath(__file__)),
                               'thirdparty', 'context', 'tex', 'texmf', 'fonts',
                               'data', 'gust', 'tex-gyre', 'pagella')
        if os.path.isdir(pagella):
            cmd += ['--font-path', pagella]
        for extra in (self.config.get('Typst', 'fontPath'),
                      os.environ.get('TYPST_FONT_PATH')):
            if extra:
                cmd += ['--font-path', extra]
        cmd += [self.typFilename, self.outputFilename]
        pp = subprocess.run(cmd, capture_output=True, text=True)
        if pp.stderr:
            self.logger.warning(pp.stderr)
        if pp.returncode != 0:
            raise RuntimeError('typst compile failed with status %d' % pp.returncode)

    #
    #   Paragraph assembly
    #


    def titleGap(self):
        # Breathing space beneath the whole book-title stack, emitted by
        # whatever block follows it.
        if self.afterTitle:
            self.afterTitle = False
            self.chunks.append('#v(18pt)\n\n')

    def emit(self, text):
        if self.para is not None:
            self.para.append(text)
        else:
            self.chunks.append(text)

    def openParagraph(self, kind):
        self.closeParagraph()
        self.titleGap()
        if kind not in ('q1', 'q2', 'q3'):
            self.stopNarrower()
        self.para = []
        self.paraKind = kind

    def closeParagraph(self):
        if self.para is None:
            return
        body = ''.join(self.para).strip()
        kind = self.paraKind
        self.para = None
        if not body:
            return
        if kind in ('q1', 'q2', 'q3'):
            self.chunks.append('#poem(' + kind[1] + ' - 1)[' + body + ']\n\n')
        elif kind == 'd':
            self.chunks.append('#align(center, emph[' + body + '])\n\n')
        elif kind == 'pi':
            self.chunks.append('#pad(left: 1.5em, right: 1.5em)[' + body + ']\n\n')
        else:
            self.chunks.append(body + '\n\n')

    def startNarrower(self, kind):
        self.closeParagraph()
        self.titleGap()
        if not self.narrower:
            self.chunks.append('#v(6.5pt)\n\n')
            self.narrower = True
        self.para = []
        self.paraKind = kind

    def stopNarrower(self):
        if self.narrower:
            self.chunks.append('#v(6.5pt)\n\n')
            self.narrower = False

    def addText(self, text):
        target = self.para if self.para is not None else self.chunks
        tail = target[-1] if target else ''
        if (tail and not tail.endswith((' ', '[', '(', '\n', '“', '‘')) and text
                and not text.startswith((' ', ',', '.', ';', ':', '!', '?',
                                         '’', '”', ')'))):
            text = ' ' + text
        self.emit(text)

    def smallCapOpening(self, s):
        # Match the ConTeXt renderer: the opening phrase (to the first
        # comma-ish break, or first space after 50 chars) in small caps.
        i = 0
        while i < len(s):
            if i < 50:
                if s[i] in ',;(' or s[i:i + 3] == 'and':
                    return ('#smallcaps[' + escapeText(s[:i + 1]) + ']'
                            + escapeText(s[i + 1:]))
            else:
                if s[i] == ' ':
                    return ('#smallcaps[' + escapeText(s[:i]) + ']'
                            + escapeText(s[i:]))
            i = i + 1
        return '#smallcaps[' + escapeText(s) + ']'

    #
    #   Token handlers
    #

    def render_id(self, token):
        self.closeParagraph()
        self.stopNarrower()
        self.cachedChapter = ''
        self.pendingSmallCaps = False

    def render_h(self, token):
        # Book start: new right-hand page, running-head marking, and a
        # hidden heading carrying the short book name into the table of
        # contents and PDF bookmarks - matching ConTeXt's hidden \chapter.
        self.closeParagraph()
        self.stopNarrower()
        value = escapeText(token.value)
        # \page[right] is a plain break in the singlesided layout.
        self.chunks.append('#pagebreak(weak: true)\n'
                           '#bookmk.update("' + value + '")\n'
                           '#chaptermk.update("")\n'
                           '#sectionmk.update("")\n'
                           '#place(hide(heading(level: 1, outlined: true)[' + value + ']))\n\n')
        self.afterTitle = False

    def render_mt1(self, token):
        self.closeParagraph()
        self.chunks.append('#align(center, text(size: 18pt)[#upper['
                           + escapeText(token.value) + ']])\n\n#v(4pt)\n\n')
        self.afterTitle = True
    def render_mt2(self, token):
        self.closeParagraph()
        self.chunks.append('#align(center, text(size: 18pt)[#upper['
                           + escapeText(token.value) + ']])\n\n#v(4pt)\n\n')
        self.afterTitle = True
    def render_mt3(self, token):
        self.closeParagraph()
        self.chunks.append('#align(center, text(size: 18pt)['
                           + escapeText(token.value) + '])\n\n#v(4pt)\n\n')

    def sectionHead(self, token, smallcaps):
        self.closeParagraph()
        self.titleGap()
        self.stopNarrower()
        value = escapeText(token.value)
        self.chunks.append('#v(16pt)\n'
                           '#sectionmk.update("' + value + '")\n'
                           '#align(center, emph[' + value + '])\n#v(6pt)\n\n')
        if smallcaps:
            self.pendingSmallCaps = True

    def render_ms1(self, token):    self.sectionHead(token, True)
    def render_ms2(self, token):    self.sectionHead(token, True)
    def render_s1(self, token):
        if token.value == '~':
            self.closeParagraph()
            self.chunks.append('#v(10pt)\n\n')
        else:
            self.sectionHead(token, False)
    def render_s2(self, token):     self.sectionHead(token, False)

    def render_p(self, token):      self.openParagraph('p')
    def render_m(self, token):      self.openParagraph('p')
    def render_pi(self, token):     self.openParagraph('pi')
    def render_d(self, token):      self.openParagraph('d')
    def render_nb(self, token):     self.openParagraph('p')
    def render_b(self, token):
        self.closeParagraph()
        self.chunks.append('#v(5pt)\n\n')

    def render_q(self, token):      self.startNarrower('q1')
    def render_q1(self, token):     self.startNarrower('q1')
    def render_q2(self, token):     self.startNarrower('q2')
    def render_q3(self, token):     self.startNarrower('q3')

    def render_c(self, token):
        value = escapeText(token.value)
        self.cachedChapter = value
        self.emit('#chaptermk.update("' + value + '")')
    def render_v(self, token):
        if token.value == '1':
            if self.cachedChapter:
                self.addText('#C("' + self.cachedChapter + '")')
                self.cachedChapter = ''
        else:
            self.addText('#V("' + escapeText(token.value) + '")')

    def render_text(self, token):
        if self.pendingSmallCaps:
            self.pendingSmallCaps = False
            self.addText(self.smallCapOpening(token.value))
        else:
            self.addText(escapeText(token.value))

    # Inline character styling
    def render_nd_s(self, token):
        if self.paraKind != 'd':
            self.addText('#smallcaps[')
    def render_nd_e(self, token):
        if self.paraKind != 'd':
            self.emit(']')
    def render_em_s(self, token):   self.addText('#emph[')
    def render_em_e(self, token):   self.emit(']')
    def render_qs_s(self, token):   self.addText('#emph[')
    def render_qs_e(self, token):   self.emit(']')
    # Words of Jesus: deliberately unstyled, as in the ConTeXt edition.
    def render_wj_s(self, token):   pass
    def render_wj_e(self, token):   pass

    # Footnotes: native Typst footnotes.
    def render_f_s(self, token):    self.emit('#footnote[')
    def render_f_e(self, token):    self.emit(']')
    def render_fr(self, token):     self.emit(escapeText(token.value) + ' ')
    def render_ft(self, token):     pass
    def render_ft_e(self, token):   pass

    def render_periph(self, token):
        if token.value == 'Table of Contents':
            self.closeParagraph()
            self.chunks.append('#pagebreak(to: "odd")\n'
                               '#align(center, text(size: 14pt)[#upper[Table of Contents]])\n'
                               '#v(10pt)\n'
                               '#outline(title: none, depth: 1)\n\n')
